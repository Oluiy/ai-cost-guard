package config

import (
	"context"
	"crypto/subtle"
	"fmt"
	"time"
)

const stateTimeout = 10 * time.Second

// persistLocked writes the current settings to wherever they live: the
// state store when one is attached, otherwise the config file (and nowhere
// at all when there's no path, as in tests). Caller holds s.mu.
func (s *Settings) persistLocked() error {
	if s.store != nil {
		ctx, cancel := context.WithTimeout(context.Background(), stateTimeout)
		defer cancel()
		return s.store.SaveState(ctx, s.cfg.State())
	}
	if s.path != "" {
		return Save(s.path, s.cfg)
	}
	return nil
}

// AttachStore makes store the home of the runtime-mutable settings.
//
// First boot (nothing stored yet): the settings in config.yaml seed the
// store, so a config generated by `fitguard init` works unchanged and
// seeded reports true. Every boot after that the store wins and the
// config's copy of those settings is ignored, which is what lets a
// dashboard edit or a password reset survive a redeploy that restarts
// from the same config.
func (s *Settings) AttachStore(ctx context.Context, store StateStore) (seeded bool, err error) {
	s.mu.Lock()
	defer s.mu.Unlock()

	st, ok, err := store.LoadState(ctx)
	if err != nil {
		return false, fmt.Errorf("loading settings from the database: %w", err)
	}
	if !ok {
		if err := store.SaveState(ctx, s.cfg.State()); err != nil {
			return false, fmt.Errorf("seeding settings into the database: %w", err)
		}
		seeded = true
	} else {
		s.cfg.applyState(st)
	}
	s.store = store
	return seeded, nil
}

// Reload re-reads the settings from the store, so a change made through
// another instance (or by `fitguard reset-dashboard-password` run
// elsewhere) takes effect here without a restart. No-op without a store.
func (s *Settings) Reload(ctx context.Context) error {
	s.mu.RLock()
	store := s.store
	s.mu.RUnlock()
	if store == nil {
		return nil
	}
	st, ok, err := store.LoadState(ctx)
	if err != nil {
		return err
	}
	if !ok {
		return nil
	}
	s.mu.Lock()
	s.cfg.applyState(st)
	s.mu.Unlock()
	return nil
}

// Dashboard returns a copy of the live dashboard login settings.
func (s *Settings) Dashboard() DashboardConfig {
	s.mu.RLock()
	defer s.mu.RUnlock()
	d := s.cfg.Dashboard
	d.Users = append([]DashboardUser(nil), d.Users...)
	return d
}

// ReplaceDashboard swaps the dashboard login settings and persists them,
// rolling back in memory if the write fails.
func (s *Settings) ReplaceDashboard(d DashboardConfig) error {
	s.mu.Lock()
	defer s.mu.Unlock()
	prev := s.cfg.Dashboard
	s.cfg.Dashboard = d
	if err := s.persistLocked(); err != nil {
		s.cfg.Dashboard = prev
		return err
	}
	return nil
}

// HasKeys reports whether any virtual key is configured. With none, the
// gateway runs unauthenticated in single-tenant mode.
func (s *Settings) HasKeys() bool {
	s.mu.RLock()
	defer s.mu.RUnlock()
	return len(s.cfg.Keys) > 0
}

// UserForKey resolves a virtual key to its user_id. It compares against
// every configured key rather than stopping at the first match, so timing
// can't reveal how close a guess was.
func (s *Settings) UserForKey(token string) (userID string, ok bool) {
	s.mu.RLock()
	defer s.mu.RUnlock()
	tokenBytes := []byte(token)
	for key, uid := range s.cfg.Keys {
		if len(key) == len(token) && subtle.ConstantTimeCompare([]byte(key), tokenBytes) == 1 {
			userID, ok = uid, true
		}
	}
	return userID, ok
}
